def test_orchestrator_progress_callback(tmp_path, monkeypatch):
    from unittest.mock import MagicMock
    from src.orchestrator import BenchmarkOrchestrator

    # Create dummy dataset
    dataset_file = tmp_path / "prompts.jsonl"
    dataset_file.write_text('{"id": 1, "prompt": "P1"}\n{"id": 2, "prompt": "P2"}\n', encoding="utf-8")

    config = BenchmarkConfig(
        models=["m1", "m2", "m3"],
        dataset_path=str(dataset_file),
        max_new_tokens=10,
        warmup_runs=0,
        output_dir=str(tmp_path / "out")
    )

    # Mock HuggingFaceRunner to avoid downloading real weights in this unit test
    mock_runner_cls = MagicMock()
    mock_runner_inst = MagicMock()
    mock_runner_inst.generate.return_value = ("Test output", 5)
    mock_runner_cls.return_value = mock_runner_inst
    monkeypatch.setattr("src.orchestrator.HuggingFaceRunner", mock_runner_cls)

    captured_events = []
    def callback(evt):
        captured_events.append(evt["event"])

    orchestrator = BenchmarkOrchestrator(config, progress_callback=callback)
    df = orchestrator.run()

    assert not df.empty
    assert "model_start" in captured_events
    assert "prompt_done" in captured_events
    assert "complete" in captured_events

