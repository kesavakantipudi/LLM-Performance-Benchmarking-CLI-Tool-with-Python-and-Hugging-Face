def test_compute_type_token_ratio():
    # Empty string
    assert compute_type_token_ratio("") == 0.0
    # All distinct words
    assert compute_type_token_ratio("The quick brown fox") == 1.0
    # Repeated words: "hello hello hello hello" -> 1 unique / 4 total = 0.25
    assert compute_type_token_ratio("hello hello hello hello") == 0.25
    # Mixed punctuation and case
    assert compute_type_token_ratio("Hello, hello! World world.") == 0.5


def test_is_degenerate_or_empty():
    assert is_degenerate_or_empty("", 0) is True
    assert is_degenerate_or_empty("   ", 0) is True
    assert is_degenerate_or_empty("Hi", 1, min_tokens=5) is True
    assert is_degenerate_or_empty("Valid sentence with several words", 6, min_tokens=5) is False


def test_profile_inference_mock():
    import time
    def mock_gen():
        time.sleep(0.01)
        return "This is a clean, coherent sample response generated by a language model.", 12

    result = profile_inference(mock_gen, min_tokens_for_degenerate=5)
    assert "latency_sec" in result
    assert result["latency_sec"] > 0
    assert result["generated_tokens"] == 12
    assert result["throughput_tps"] > 0
    assert result["peak_ram_bytes"] > 0
    assert result["peak_ram_mb"] > 0
    assert result["type_token_ratio"] > 0.5
    assert result["is_degenerate"] is False


def test_config_parser_valid_yaml(tmp_path):
    # Create valid dataset
    dataset_file = tmp_path / "prompts.jsonl"
    dataset_file.write_text('{"id": 1, "prompt": "Test prompt"}\n', encoding="utf-8")

    # Create valid config
    config_file = tmp_path / "config.yaml"
    config_file.write_text(f"""
models:
  - "model-1"
  - "model-2"
  - "model-3"
dataset_path: "{str(dataset_file).replace(chr(92), '/')}"
max_new_tokens: 40
""", encoding="utf-8")

    cfg = load_config(str(config_file))
    assert len(cfg.models) == 3
    assert cfg.max_new_tokens == 40
    assert cfg.dataset_path == str(dataset_file).replace(chr(92), '/')


def test_config_parser_insufficient_models(tmp_path):
    dataset_file = tmp_path / "prompts.jsonl"
    dataset_file.write_text('{"id": 1, "prompt": "Test"}\n', encoding="utf-8")

    config_file = tmp_path / "invalid_config.yaml"
    config_file.write_text(f"""
models:
  - "model-1"
  - "model-2"
dataset_path: "{str(dataset_file).replace(chr(92), '/')}"
""", encoding="utf-8")

    with pytest.raises(ValueError, match="at least three distinct model identifiers"):
        load_config(str(config_file))


